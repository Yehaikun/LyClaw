package lyjew.com.lyclaw.storage;

/**
 * 全文搜索引擎类型枚举，定义了记忆和知识库存储中可用的全文检索实现方案。
 *
 * <p>在 LyClaw 框架的记忆检索体系中，除了基于向量相似度的语义搜索外，全文搜索
 * （Full-Text Search）也是重要的检索手段。全文搜索基于关键词匹配和文本倒排索引，
 * 能够精确查找包含特定关键词的记忆或文档，与语义搜索互补，共同构成混合检索策略。
 * 本枚举定义了框架内置支持的三种全文搜索引擎实现，从轻量级本地算法到重量级分布式
 * 搜索引擎，满足不同规模和性能要求的部署场景。
 *
 * <p>三种搜索引擎类型：
 * <ul>
 *   <li><b>BM25（Best Matching 25）</b>：经典的基于概率检索模型的排序函数，是 TF-IDF
 *       的改进版本。BM25 考虑了词频饱和度和文档长度归一化，能有效避免长文档的偏向
 *       问题。使用纯 Java 实现，无需外部依赖，适合内嵌式的轻量级全文搜索场景。
 *       支持自定义参数 k1（词频饱和度控制）和 b（长度归一化因子）</li>
 *   <li><b>TF_IDF（Term Frequency-Inverse Document Frequency）</b>：基于词频-逆文档
 *       频率的经典信息检索算法。词频（TF）衡量词语在文档中的出现频率，逆文档频率
 *       （IDF）衡量词语在整个文档集合中的稀有程度，两者结合评估词语对文档的重要性。
 *       作为最简单直接的全文检索方案，适合快速原型开发和对检索精度要求不高的场景</li>
 *   <li><b>ELASTICSEARCH</b>：基于 Elasticsearch 分布式搜索引擎的全文检索实现。
 *       Elasticsearch 底层使用 Apache Lucene 倒排索引引擎，提供强大的全文搜索能力，
 *       包括分词器定制、同义词处理、模糊匹配、高亮显示、聚合分析等企业级特性。
 *       适合大规模记忆库、多节点集群部署、高并发检索的生产环境。需要在配置中指定
 *       Elasticsearch 集群的连接地址</li>
 * </ul>
 *
 * <p>在框架配置中通过指定 FullTextEngine 类型来选择具体的搜索引擎实现。不同引擎实现的
 * 配置参数和依赖要求不同：BM25 和 TF_IDF 可在无外部依赖的情况下开箱即用，Elasticsearch
 * 需要额外配置 ES 集群连接信息和索引映射。
 */
public enum FullTextEngine {
    BM25,
    TF_IDF,
    ELASTICSEARCH
}
