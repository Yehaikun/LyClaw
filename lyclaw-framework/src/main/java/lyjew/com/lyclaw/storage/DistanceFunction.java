package lyjew.com.lyclaw.storage;

/**
 * 向量距离函数枚举，定义了向量存储与检索中用于计算向量间相似度/距离的算法类型。
 *
 * <p>在 LyClaw 框架的记忆和知识库存储体系中，文本通过 Embedding 模型转换为高维向量
 * 后存入向量数据库。当需要检索与查询最相关的记忆或知识时，系统需要计算查询向量与
 * 存储向量之间的"距离"或"相似度"，以此作为排序和筛选的依据。不同的距离函数适用于
 * 不同的向量空间特性和应用场景，选择合适的距离函数对检索精度有显著影响。
 *
 * <p>本枚举支持的四种距离函数：
 * <ul>
 *   <li><b>COSINE（余弦距离/相似度）</b>：计算两个向量之间夹角的余弦值，取值范围 [-1, 1]，
 *       值越接近 1 表示向量方向越一致。余弦相似度对向量的绝对长度不敏感，只关注方向，
 *       是 NLP 和文本相似度计算中最常用的度量方式，特别适用于基于 Transformer 架构
 *       的 Embedding 模型产生的向量。推荐作为文本语义搜索的默认选择</li>
 *   <li><b>EUCLIDEAN（欧几里得距离）</b>：计算两个向量在多维空间中的直线距离
 *       （L2 范数），取值 [0, +infinity)。欧氏距离对向量的绝对位置和长度都敏感，
 *       适用于向量已经过 L2 归一化的场景，以及需要考虑向量绝对值大小（如向量
 *       代表物理量）的应用。在文本场景中通常需要配合向量归一化使用</li>
 *   <li><b>DOT_PRODUCT（点积/内积）</b>：计算两个向量的点积，即对应元素乘积之和。
 *       点积同时考虑了向量的方向和长度，值越大表示两个向量越相似。对于已归一化的
 *       向量，点积等价于余弦相似度（因为归一化向量的模长为 1）。点积计算效率高于
 *       余弦距离（无需计算模长），适合高性能检索场景</li>
 *   <li><b>MANHATTAN（曼哈顿距离）</b>：计算两个向量在各维度上差的绝对值之和
 *       （L1 范数），又称城市街区距离。相比于欧氏距离，曼哈顿距离对异常值（离群点）
 *       的敏感度较低，在高维稀疏向量的场景中有时能提供更好的检索效果，同时也是
 *       某些向量数据库（如 Milvus）支持的内置距离类型</li>
 * </ul>
 *
 * <p>在向量数据库配置中使用此枚举指定默认的距离计算方式。不同的向量数据库对距离函数
 * 的支持程度不同，配置时应确保所选函数与目标数据库兼容。
 */
public enum DistanceFunction {
    COSINE,
    EUCLIDEAN,
    DOT_PRODUCT,
    MANHATTAN
}
