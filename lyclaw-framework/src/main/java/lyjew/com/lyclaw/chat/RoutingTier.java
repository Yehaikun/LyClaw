package lyjew.com.lyclaw.chat;

/**
 * 路由层级枚举（Routing Tier），按请求的复杂度从低到高划分，用于智能路由策略的决策依据。
 *
 * <p>在 LyClaw 框架的多模型路由体系中，不同的 AI 模型具有不同的能力等级、成本和性能特征。
 * 简单的小模型（如 gpt-4o-mini、deepseek-v4-flash）成本低、响应快但推理能力有限，
 * 适合处理问候、闲聊等简单对话；强大的大模型（如 gpt-4o、deepseek-v4）推理能力强但
 * 成本高、延迟大，适合处理复杂分析、深度推理等任务。RoutingTier 枚举将请求按复杂度
 * 划分为四个层级，路由策略（{@link ModelRouter}）根据请求的内容特征（如长度、关键词、
 * 意图分类等）将其归类到对应的层级，从而将请求智能地分配到成本-性能最优的模型上，
 * 在保证回复质量的同时降低整体调用成本。
 *
 * <p>四个路由层级及其用途：
 * <ul>
 *   <li><b>SIMPLE（简单层级）</b>：适用于问候语、日常寒暄、简单问答等低复杂度请求。
 *       这类请求对推理能力要求极低，通常只需模式匹配即可回答。路由策略会将此层级的
 *       请求分配给成本最低的小型模型，以最小化 Token 消耗和响应延迟</li>
 *   <li><b>STANDARD（标准层级）</b>：适用于一般的知识问答、信息检索、文本总结等中等
 *       复杂度请求。这类请求需要一定的语言理解和生成能力，是大多数对话场景的默认层级。
 *       路由至此层级的请求会分配给框架配置的默认主力模型</li>
 *   <li><b>COMPLEX（复杂层级）</b>：适用于需要深度推理、多步分析、逻辑推导、数学计算
 *       等高复杂度请求。这类请求对模型的推理能力和知识广度要求较高。路由策略会将此
 *       层级的请求分配给能力最强的大型模型，必要时启用思考模式（思维链）增强推理</li>
 *   <li><b>CODE（代码层级）</b>：专门用于代码生成、代码审查、Bug 修复、架构设计等
 *       编程相关请求。由于代码任务具有独特的领域特征（语法结构、类型系统、工程约束），
 *       路由策略会将此层级的请求分配给经过代码训练优化的专长模型，以获得最佳的代码
 *       生成质量和准确率</li>
 * </ul>
 *
 * @see ModelRouter
 * @see RoutingDecision
 * @see FirstAvailableRouter
 */
public enum RoutingTier {
    SIMPLE,
    STANDARD,
    COMPLEX,
    CODE
}
