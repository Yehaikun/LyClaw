package lyjew.com.lyclaw.reflect;

/**
 * 质量评估器接口，从准确性、完整性、安全性和用户体验四个维度对模型输出进行定量评分。
 *
 * <p><b>在反思系统中的角色</b>：QualityEvaluator 是反思系统中"诊断阶段"的核心组件。
 * 它独立于错误检测和策略调整，专注于对模型输出质量的量化评估。
 * 每个维度返回一个 0.0~1.0 的评分，越高表示质量越好。
 * {@link ReflectionEngine} 将四个维度的评分聚合为 {@link QualityAssessment} 对象，
 * 进而存储在 {@link ReflectionReport} 中供后续决策使用。</p>
 *
 * <p><b>四维评分方法的设计理念</b>：四个维度从不同角度审视模型输出质量，
 * 覆盖了"对不对"（准确性）、"全不全"（完整性）、"安不安全"（安全性）、
 * "好不好用"（用户体验）四个基本质量要素。这种多维度的评估方法避免了
 * 单一指标可能导致的片面评判，例如一个准确但不完整的输出和一个完整但有错误的输出，
 * 在综合评分上会体现出不同的缺陷特性。</p>
 *
 * <p><b>实现建议</b>：
 * <ul>
 *   <li>准确性评估可以结合多种技术：与期望输出的文本相似度（如 BLEU、ROUGE 等指标）、
 *       关键事实的逐条核对、以及通过搜索引擎或知识库进行的事实交叉验证</li>
 *   <li>完整性评估可以通过检查任务描述中的关键要求点是否都在输出中有对应内容，
 *       以及输出结构是否包含所有必要的段落来实现</li>
 *   <li>安全性评估应包含多层次的安全检查：关键词/模式匹配（基础层）、
 *       内容分类模型（中间层）、以及外部安全 API 调用（高级层）</li>
 *   <li>用户体验评估可以从文本结构（是否有清晰的标题和段落）、
 *       格式正确性（JSON/Markdown 是否合法）、语言流畅度、以及输出长度合理性
 *       等方面进行</li>
 * </ul>
 *
 * <p><b>评分标准的开放性</b>：此接口只定义了四个评分方法的签名和返回范围，
 * 具体的评分算法和标准留给实现类决定。这允许不同的 LLM 提供商、不同的任务类型、
 * 甚至不同的质量要求级别使用不同的评估器实现。
 * 例如，医疗场景的质量评估器可能对安全性的权重远高于用户体验，
 * 而创意写作场景则相反。</p>
 *
 * @see QualityAssessment 质量评估结果实体，四个评分的聚合载体
 * @see ReflectionEngine 反思引擎，调用质量评估器并聚合结果
 * @see StrategyAdjuster 策略调整器，根据质量评分制定调整方案
 */
public interface QualityEvaluator {

    /**
     * 评估输出的准确性：将模型的实际输出与期望输出进行比对。
     *
     * <p>此方法的核心任务是对比两个文本的语义一致性。实现时可以考虑：
     * <ul>
     *   <li>使用 n-gram 重叠率（BLEU/ROUGE）进行文本相似度计算</li>
     *   <li>使用嵌入向量的余弦相似度进行语义相似度比较</li>
     *   <li>提取关键事实并进行逐条核实（如数值、日期、名称是否正确）</li>
     *   <li>在期望输出为 null 或空字符串时，回退到基于规则或常识的准确性评估</li>
     * </ul>
     * </p>
     *
     * @param output   模型实际生成的输出文本，不能为 {@code null}
     * @param expected 期望输出文本，作为准确性评估的参考基准。
     *                 可以为 {@code null} 或空字符串，此时实现应使用替代评估策略
     * @return 准确性评分（0.0~1.0），0.0 表示完全不准确，1.0 表示完全匹配
     */
    double evaluateAccuracy(String output, String expected);

    /**
     * 评估输出的完整性：检查模型输出是否覆盖了任务描述中的所有要求。
     *
     * <p>此方法评估的是输出在信息覆盖面上的完整程度，而非篇幅长短。
     * 实现时可以考虑：将任务描述拆解为多个关键要求点，逐一检查输出是否覆盖；
     * 检查输出是否包含预期的结构段落（如是否包含"分析"、"方案"、"总结"等部分）；
     * 识别输出中是否存在明显的信息遗漏（如只回答了问题的一部分）。</p>
     *
     * @param output          模型实际生成的输出文本，不能为 {@code null}
     * @param taskDescription 任务描述或用户原始请求，用于提取评估完整性所需的要求清单。
     *                        可以为 {@code null} 或空字符串，此时实现应使用
     *                        输出文本自身的结构完整性作为评估标准
     * @return 完整性评分（0.0~1.0），0.0 表示严重不完整，1.0 表示完全覆盖所有要求
     */
    double evaluateCompleteness(String output, String taskDescription);

    /**
     * 评估输出的安全性：检查模型输出是否包含不安全或有害内容。
     *
     * <p>安全性评估是一个多层次的检测过程，实现时应考虑：
     * <ul>
     *   <li><b>基础层</b>：敏感关键词和正则模式匹配（如检测手机号、身份证号、
     *       邮箱地址等个人信息的意外泄露）</li>
     *   <li><b>内容层</b>：检测暴力、色情、仇恨言论、非法建议等有害内容</li>
     *   <li><b>上下文层</b>：检查输出在对话上下文中是否构成安全风险
     *       （如虽然单条回复无害，但与历史对话结合后形成越狱攻击）</li>
     *   <li><b>合规层</b>：检查是否违反了特定领域的使用规范
     *       （如医疗建议的免责声明缺失、金融建议的合规性等）</li>
     * </ul>
     * 安全性评分低于 0.5 通常应触发 {@code TRIGGER_HUMAN_INTERVENTION}
     * 级别的策略调整。</p>
     *
     * @param output 模型实际生成的输出文本，不能为 {@code null}
     * @return 安全性评分（0.0~1.0），0.0 表示存在严重安全问题，1.0 表示完全安全
     */
    double evaluateSafety(String output);

    /**
     * 评估输出的用户体验：从可读性、格式规范性、语气友好度等方面评分。
     *
     * <p>用户体验评估关注的是输出作为信息产品对用户的友好程度，而非内容的正确性。
     * 实现时可以考虑以下指标：
     * <ul>
     *   <li><b>可读性</b>：输出是否有清晰的段落分隔、是否使用了适当的标题和列表、
     *       语句是否通顺自然、是否有过多的技术 jargon 导致理解困难</li>
     *   <li><b>格式规范性</b>：如果预期输出为 JSON，JSON 是否合法且格式化良好；
     *       如果预期输出为 Markdown，Markdown 语法是否正确</li>
     *   <li><b>信息密度</b>：输出是否提供了足够有价值的信息，避免过度冗长或过于简略</li>
     *   <li><b>语气友好度</b>：输出语气是否礼貌、积极、有建设性，是否存在冷漠或
     *       敷衍的表述</li>
     *   <li><b>操作引导性</b>：输出是否包含了清晰的下一步建议或操作指引，
     *       帮助用户知道接下来该做什么</li>
     * </ul>
     * </p>
     *
     * @param output 模型实际生成的输出文本，不能为 {@code null}
     * @return 用户体验评分（0.0~1.0），0.0 表示体验极差（混乱、不友好），
     *         1.0 表示体验极佳（清晰、友好、易于消费）
     */
    double evaluateUserExperience(String output);
}
