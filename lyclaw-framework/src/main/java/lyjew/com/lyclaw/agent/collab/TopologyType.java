package lyjew.com.lyclaw.agent.collab;

/**
 * 网络拓扑类型枚举，定义多代理协作中代理间的通信结构。
 *
 * 不同的拓扑类型决定了代理之间消息路由的方式：STAR（星型）有一个
 * 中心协调代理，其余代理通过中心转发；MESH（网状）每对代理直连，
 * 适合对等协商；HIERARCHICAL（层级）按树状结构分层通信，适合大型
 * 任务的逐层分解；HYBRID（混合）结合多种拓扑，用于复杂动态场景。
 * 协作模式声明其首选拓扑，编排器在自动匹配模式下会考虑拓扑兼容性。
 */
public enum TopologyType {
    /** 星型拓扑：一个中心代理协调所有工作代理 */
    STAR,
    /** 网状拓扑：所有代理两两直连，全对等通信 */
    MESH,
    /** 层级拓扑：代理按树状结构分层，逐级下发和汇总 */
    HIERARCHICAL,
    /** 混合拓扑：根据不同任务阶段动态切换拓扑结构 */
    HYBRID
}
