package lyjew.com.lyclaw.memory;

/**
 * 记忆分类枚举，标识记忆条目所承载的知识类型。
 *
 * 不同分类的记忆在检索和固化阶段可能采用不同的权重策略，
 * 例如偏好类记忆在对话中可能比事实类记忆更优先注入上下文。
 */
public enum MemoryCategory {
    /** 事实性知识（如 "北京是中国的首都"） */
    FACT,
    /** 用户偏好（如 "用户喜欢简洁的代码风格"） */
    PREFERENCE,
    /** 事件记录（如 "上周五用户部署了服务"） */
    EVENT,
    /** 经验教训（如 "上次使用该库时遇到了兼容性问题"） */
    LESSON,
    /** 待办任务（如 "用户计划下周重构认证模块"） */
    TASK,
    /** 实体关系（如 "张三 是 李四 的同事"） */
    RELATION,
    /** 目标（如 "用户希望在年底前完成系统迁移"） */
    GOAL
}
